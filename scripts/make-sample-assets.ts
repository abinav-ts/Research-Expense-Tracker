// REQ-DEMO-03: embeds the synthetic UPI screenshot in the Worker so the public sample claim needs no storage.
// Run `node scripts/make-sample-assets.ts` after changing fixtures/upi-success.png.
import { readFileSync, writeFileSync } from 'node:fs';

const png = readFileSync(new URL('../fixtures/upi-success.png', import.meta.url)).toString('base64');
const out = `// GENERATED by scripts/make-sample-assets.ts from fixtures/upi-success.png (synthetic). Do not edit.\nexport const SAMPLE_UPI_PNG_BASE64 =\n  '${png}';\n`;
writeFileSync(new URL('../src/server/claims/sample-assets.ts', import.meta.url), out);
console.log(`wrote src/server/claims/sample-assets.ts (${png.length} characters)`);
